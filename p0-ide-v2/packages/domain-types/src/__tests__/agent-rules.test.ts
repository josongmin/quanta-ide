import { describe, it, expect, vi, beforeEach } from "vitest";

// ---------------------------------------------------------------------------
// Fresh store per test via dynamic import.
// ---------------------------------------------------------------------------

async function freshRulesStore() {
  const mod = await import("../agent-rules/model/rules-store");
  return mod.rulesStore;
}

async function freshParser() {
  const mod = await import("../agent-rules/model/parser");
  return mod;
}

async function freshAdapters() {
  const mod = await import("../agent-rules/model/adapters");
  return mod;
}

describe("agent-rules", () => {
  beforeEach(() => {
    vi.resetModules();
  });

  // -- rulesStore --

  it("rulesStore.rebuild produces valid targets with artifacts", async () => {
    const store = await freshRulesStore();
    store.rebuild();
    const s = store.get();
    expect(s.targets.length).toBeGreaterThan(0);
    expect(s.build.artifacts.length).toBeGreaterThan(0);
    for (const a of s.build.artifacts) {
      expect(a.output.length).toBeGreaterThan(0);
      expect(typeof a.targetId).toBe("string");
    }
  });

  it("rulesStore.setSource updates the source and re-builds", async () => {
    const store = await freshRulesStore();
    const newSource = "## Simple Rule\n\nKeep it simple.\n";
    store.setSource(newSource);
    const s = store.get();
    expect(s.source).toBe(newSource);
    expect(s.doc.sections.length).toBe(1);
    expect(s.doc.sections[0].title).toBe("Simple Rule");
  });

  // -- parser --

  it("parser parses frontmatter and sections correctly", async () => {
    const { parseRules } = await freshParser();
    const raw = `---
name: My Rules
version: 2
scope: monorepo
---

## Commands

Build: \`pnpm build\`

## Style

- TypeScript strict.
`;
    const doc = parseRules(raw);
    expect(doc.meta.name).toBe("My Rules");
    expect(doc.meta.version).toBe(2);
    expect(doc.meta.scope).toBe("monorepo");
    expect(doc.sections).toHaveLength(2);
    expect(doc.sections[0].title).toBe("Commands");
    expect(doc.sections[1].title).toBe("Style");
  });

  it("parser handles source without frontmatter", async () => {
    const { parseRules } = await freshParser();
    const doc = parseRules("## Hello\n\nWorld.\n");
    expect(doc.meta.name).toBe("Project Rules");
    expect(doc.meta.version).toBe(1);
    expect(doc.sections).toHaveLength(1);
    expect(doc.sections[0].title).toBe("Hello");
  });

  // -- adapters --

  it("claudeAdapter render includes frontmatter and generated header", async () => {
    const { claudeAdapter, cursorAdapter } = await freshAdapters();
    const { parseRules } = await freshParser();
    const doc = parseRules("---\nname: Test\nversion: 1\n---\n\n## Section\n\nBody.\n");

    const claudeResult = claudeAdapter.render(doc);
    expect(claudeResult.output).toContain("Generated by Quanta");
    expect(claudeResult.output).toContain("name: Test");
    expect(claudeResult.output).toContain("Section");

    const cursorResult = cursorAdapter.render(doc);
    expect(cursorResult.output).toContain("Test");
    expect(cursorResult.output).toContain("Generated by Quanta");
  });
});
