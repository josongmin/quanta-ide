import { parseRules } from "./parser";
import type {
  Adapter,
  AdapterCapabilities,
  Diagnostic,
  RenderResult,
  RulesDocument,
  RulesSection,
} from "./types";

function renderSection(s: RulesSection, opts: { includeScope?: boolean } = {}): string {
  const scopeSuffix = opts.includeScope && s.scope ? ` — applies to \`${s.scope}\`` : "";
  return `${"#".repeat(s.level)} ${s.title}${scopeSuffix}\n\n${s.body}`;
}

function filterUnsupported(
  doc: RulesDocument,
  cap: AdapterCapabilities,
  adapterId: string,
): { sections: RulesSection[]; diagnostics: Diagnostic[] } {
  const kept: RulesSection[] = [];
  const diags: Diagnostic[] = [];
  for (const s of doc.sections) {
    if (s.capabilities.includes("tool-permission") && !cap.supportsToolPermission) {
      diags.push({
        kind: "unsupported",
        sectionTitle: s.title,
        targetId: adapterId,
        message: `"${s.title}" uses tool-permission — not supported by ${adapterId}, section skipped.`,
      });
      continue;
    }
    if (s.scope && !cap.supportsScoped) {
      diags.push({
        kind: "scope",
        sectionTitle: s.title,
        targetId: adapterId,
        message: `"${s.title}" is scoped to \`${s.scope}\` — ${adapterId} applies rules globally.`,
      });
    }
    kept.push(s);
  }
  return { sections: kept, diagnostics: diags };
}

export const claudeAdapter: Adapter = {
  id: "claude",
  label: "Claude",
  outputPath: "CLAUDE.md",
  capabilities: {
    supportsFrontmatter: true,
    supportsToolPermission: true,
    supportsScoped: true,
  },
  parse: parseRules,
  render(doc): RenderResult {
    const { sections, diagnostics } = filterUnsupported(doc, this.capabilities, this.id);
    const header = `<!-- Generated by Quanta · do not edit — source: .agent/rules.md -->\n`;
    const fm = [
      "---",
      `name: ${doc.meta.name}`,
      `version: ${doc.meta.version}`,
      ...(doc.meta.scope ? [`scope: ${doc.meta.scope}`] : []),
      "---",
      "",
    ].join("\n");
    const body = sections.map((s) => renderSection(s, { includeScope: true })).join("\n\n");
    return { output: `${header}${fm}\n${body}\n`, diagnostics };
  },
};

