export const BUILTIN_ADAPTERS: readonly Adapter[] = [
  claudeAdapter,
  cursorAdapter,
  copilotAdapter,
  neutralAdapter,
];

export function getAdapter(id: string): Adapter | undefined {
  return BUILTIN_ADAPTERS.find((a) => a.id === id);
}
